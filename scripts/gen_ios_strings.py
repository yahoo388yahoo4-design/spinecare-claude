"""Generate ios/SpineCare/Core/Strings.swift from the Android I18n.kt maps so
both apps ship identical English/Romanian text. Run after editing I18n.kt:
    python scripts/gen_ios_strings.py
Kotlin format specifiers are converted for String(format:): %s -> %@, %d -> %ld.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = (ROOT / "android/app/src/main/java/com/spinecare/app/I18n.kt").read_text(encoding="utf-8")
en_src, ro_src = src.split("val RO")
pair = re.compile(r'"([a-z0-9_]+)" to "((?:[^"\\]|\\.)*)"')


def conv(s):
    s = s.replace("%s", "%@")
    s = re.sub(r"%(0?\d*)d", r"%\1ld", s)
    return s


def block(part):
    rows = [f'        "{k}": "{conv(v)}",' for k, v in pair.findall(part)]
    return "\n".join(rows)


out = f'''// GENERATED by scripts/gen_ios_strings.py from android/.../I18n.kt. Do not edit by hand.
import Foundation

/// In-app English/Romanian strings with a language switch independent of the system language.
final class L: ObservableObject {{
    static let shared = L()
    @Published var lang: String {{ didSet {{ UserDefaults.standard.set(lang, forKey: "lang") }} }}

    private init() {{
        lang = UserDefaults.standard.string(forKey: "lang")
            ?? (Locale.current.language.languageCode?.identifier == "ro" ? "ro" : "en")
    }}

    static var lang: String {{ shared.lang }}
    static func toggle() {{ shared.lang = shared.lang == "en" ? "ro" : "en" }}
    static func t(_ key: String) -> String {{ (shared.lang == "ro" ? ro[key] : nil) ?? en[key] ?? key }}
    static func f(_ key: String, _ args: CVarArg...) -> String {{ String(format: t(key), arguments: args) }}

    static let en: [String: String] = [
{block(en_src)}
    ]

    static let ro: [String: String] = [
{block(ro_src)}
    ]
}}
'''
(ROOT / "ios/SpineCare/Core/Strings.swift").write_text(out, encoding="utf-8")
print("wrote Strings.swift")
